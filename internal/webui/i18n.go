var langs = map[string]*lang{"en": en, "tr": tr}

func language(code string) *lang {
	if l, ok := langs[strings.ToLower(code)]; ok {
		return l
	}
	return en
}

func (l *lang) t(key string, args ...any) string {
	msg, ok := l.messages[key]
	if !ok {
		msg = key
	}
	if len(args) > 0 {
		return fmt.Sprintf(msg, args...)
	}
	return msg
}
